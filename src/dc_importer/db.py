import hashlib
import os
from pathlib import Path

import psycopg
from dotenv import load_dotenv
from psycopg.conninfo import conninfo_to_dict

PROJECT_REF = "djayrdiyastspmoaqkml"
ROOT = Path(__file__).resolve().parents[2]


def connect() -> psycopg.Connection:
    load_dotenv(ROOT / ".env", override=True)
    expected = os.getenv("SUPABASE_PROJECT_REF", PROJECT_REF)
    if expected != PROJECT_REF:
        raise ValueError("SUPABASE_PROJECT_REF does not match this repository's target project")
    dsn = os.getenv("SUPABASE_DB_URL")
    if not dsn:
        raise ValueError("Set SUPABASE_DB_URL in the new project's .env or GitHub Actions secret")
    try:
        parts = conninfo_to_dict(dsn)
    except psycopg.Error as exc:
        raise ValueError("Invalid PostgreSQL connection string") from exc
    host = parts.get("host", "")
    username = parts.get("user", "")
    direct = host == f"db.{PROJECT_REF}.supabase.co"
    pooled = host.endswith(".pooler.supabase.com") and username.endswith(f".{PROJECT_REF}")
    if not (direct or pooled):
        raise ValueError("Connection must target the dedicated Supabase project's host/account")
    if parts.get("sslmode") not in {"require", "verify-ca", "verify-full"}:
        raise ValueError("Hosted connections require sslmode=require or stronger")
    try:
        return psycopg.connect(dsn, autocommit=True, connect_timeout=15)
    except psycopg.Error as exc:
        raise ValueError(
            "Database connection failed; verify the connection settings in .env"
        ) from exc


def check_identity(conn: psycopg.Connection) -> None:
    row = conn.execute(
        "select application,project_ref from ingestion.deployment where singleton"
    ).fetchone()
    if row != ("duel-commander-data", PROJECT_REF):
        raise ValueError("Database deployment marker does not match this project")


def migrations() -> list[Path]:
    return sorted((ROOT / "supabase" / "migrations").glob("*.sql"))


def migrate(conn: psycopg.Connection) -> list[str]:
    applied = []
    with conn.transaction():
        conn.execute("select pg_advisory_xact_lock(hashtextextended('dc:migrations',0))")
        marker = conn.execute("select to_regclass('ingestion.deployment')").fetchone()[0]
        if marker:
            check_identity(conn)
        conn.execute("create schema if not exists ingestion")
        conn.execute("revoke all on schema ingestion from public")
        conn.execute("""create table if not exists ingestion.schema_migrations (
            filename text primary key, sha256 text not null,
            applied_at timestamptz not null default now())""")
        for path in migrations():
            body = path.read_text(encoding="utf-8")
            checksum = hashlib.sha256(body.encode()).hexdigest()
            previous = conn.execute(
                "select sha256 from ingestion.schema_migrations where filename=%s", (path.name,)
            ).fetchone()
            if previous:
                if previous[0] != checksum:
                    raise ValueError(f"Applied migration changed: {path.name}")
                continue
            conn.execute(body)
            conn.execute(
                "insert into ingestion.schema_migrations(filename,sha256) values (%s,%s)",
                (path.name, checksum),
            )
            applied.append(path.name)
        check_identity(conn)
    return applied


def build_sql() -> str:
    """SQL-editor alternative with the same checksums as the migration runner."""
    chunks = [
        "-- Generated by dc-data build-sql; apply ONCE to the dedicated empty project.\nBEGIN;",
        "create schema if not exists ingestion;",
        "revoke all on schema ingestion from public;",
        "create table if not exists ingestion.schema_migrations (filename text primary key, "
        "sha256 text not null, applied_at timestamptz not null default now());",
    ]
    for path in migrations():
        body = path.read_text(encoding="utf-8")
        checksum = hashlib.sha256(body.encode()).hexdigest()
        chunks.extend(
            [
                f"-- {path.name}\n{body}",
                f"insert into ingestion.schema_migrations(filename,sha256) "
                f"values ('{path.name}','{checksum}');",
            ]
        )
    chunks.append("COMMIT;\n")
    return "\n\n".join(chunks)
